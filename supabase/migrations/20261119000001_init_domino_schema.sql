-- ============================================================
-- DOMINO Landing Page & Admin CMS — Supabase PostgreSQL Schema
-- All tables prefixed with `ladi_` to avoid conflicts with existing tables
-- ============================================================

-- 1. Admin Accounts
CREATE TABLE IF NOT EXISTS public.ladi_admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'superadmin',
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TIMESTAMPTZ,
  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Leads / Dataform (UNIQUE on normalized E.164 phone number)
CREATE TABLE IF NOT EXISTS public.ladi_leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  phone_raw TEXT NOT NULL DEFAULT '',
  country_iso TEXT NOT NULL DEFAULT 'VN',
  dial_code TEXT NOT NULL DEFAULT '+84',
  phone_e164 TEXT NOT NULL UNIQUE,
  phone_national TEXT NOT NULL DEFAULT '',
  stage TEXT NOT NULL DEFAULT '',
  area TEXT NOT NULL DEFAULT '',
  need TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'new',
  notes TEXT NOT NULL DEFAULT '',
  utm_source TEXT NOT NULL DEFAULT '',
  utm_medium TEXT NOT NULL DEFAULT '',
  utm_campaign TEXT NOT NULL DEFAULT '',
  utm_content TEXT NOT NULL DEFAULT '',
  utm_term TEXT NOT NULL DEFAULT '',
  fbclid TEXT NOT NULL DEFAULT '',
  fbp TEXT NOT NULL DEFAULT '',
  fbc TEXT NOT NULL DEFAULT '',
  fb_event_id TEXT NOT NULL DEFAULT '',
  fb_capi_status TEXT NOT NULL DEFAULT 'skipped',
  fb_capi_response TEXT NOT NULL DEFAULT '',
  landing_url TEXT NOT NULL DEFAULT '',
  referrer TEXT NOT NULL DEFAULT '',
  ip_address TEXT NOT NULL DEFAULT '',
  user_agent TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ladi_leads_created_at ON public.ladi_leads (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ladi_leads_status ON public.ladi_leads (status);
CREATE INDEX IF NOT EXISTS idx_ladi_leads_utm_source ON public.ladi_leads (utm_source);

-- 3. Facebook Conversion Events Log (Pixel + CAPI)
CREATE TABLE IF NOT EXISTS public.ladi_conversion_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT REFERENCES public.ladi_leads(id) ON DELETE SET NULL,
  event_name TEXT NOT NULL,
  event_id TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'server',
  fbclid TEXT NOT NULL DEFAULT '',
  fbp TEXT NOT NULL DEFAULT '',
  fbc TEXT NOT NULL DEFAULT '',
  utm_source TEXT NOT NULL DEFAULT '',
  utm_campaign TEXT NOT NULL DEFAULT '',
  event_source_url TEXT NOT NULL DEFAULT '',
  value DOUBLE PRECISION NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'VND',
  capi_status TEXT NOT NULL DEFAULT 'skipped',
  capi_http_code INTEGER NOT NULL DEFAULT 0,
  capi_response TEXT NOT NULL DEFAULT '',
  ip_address TEXT NOT NULL DEFAULT '',
  user_agent TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ladi_conv_created_at ON public.ladi_conversion_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ladi_conv_event_name ON public.ladi_conversion_events (event_name);

-- 4. Site Settings (SEO + Facebook Pixel/CAPI config)
CREATE TABLE IF NOT EXISTS public.ladi_site_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. CMS Live Preview Overrides
CREATE TABLE IF NOT EXISTS public.ladi_cms_overrides (
  cms_key TEXT PRIMARY KEY,
  cms_type TEXT NOT NULL DEFAULT 'text',
  value_json TEXT NOT NULL,
  updated_by TEXT NOT NULL DEFAULT 'admin',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. CMS Revision History
CREATE TABLE IF NOT EXISTS public.ladi_cms_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_json TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL DEFAULT 'admin',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Media Library Assets
CREATE TABLE IF NOT EXISTS public.ladi_media_assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename TEXT NOT NULL UNIQUE,
  original_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  size_bytes INTEGER NOT NULL,
  url TEXT NOT NULL,
  uploaded_by TEXT NOT NULL DEFAULT 'admin',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. Security Audit Logs
CREATE TABLE IF NOT EXISTS public.ladi_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  target TEXT NOT NULL DEFAULT '',
  detail TEXT NOT NULL DEFAULT '',
  ip_address TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ladi_audit_created_at ON public.ladi_audit_logs (created_at DESC);

-- ============================================================
-- ROW LEVEL SECURITY (RLS) — LOCK DOWN DIRECT CLIENT ACCESS
-- Only Express Backend (using SUPABASE_SERVICE_ROLE_KEY) can access tables.
-- ============================================================
ALTER TABLE public.ladi_admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_conversion_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_site_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_cms_overrides ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_cms_revisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_media_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ladi_audit_logs ENABLE ROW LEVEL SECURITY;

